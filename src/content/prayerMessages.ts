/** رسالة الصلاة لليوم (تتبدل يوميًا، وثابتة في اليوم نفسه) */
export function prayerMessage(p: PrayerKey, seed: number): PrayerMessage {
  const list = PRAYER_MESSAGES[p]
  return list[Math.abs(seed) % list.length]
}
